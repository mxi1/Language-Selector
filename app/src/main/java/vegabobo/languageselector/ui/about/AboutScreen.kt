private const val GITHUB_URL = "https://github.com/VegaBobo/Language-Selector"
private val AboutContentMaxWidth = 720.dp

/**
 * About screen: application identity/version, the GitHub repository link and the list of
 * bundled libraries generated by aboutlibraries. Width is capped on wide windows.
 */
@Composable
fun AboutScreen(
    onBack: () -> Unit,
    showBackButton: Boolean,
) {
    val context = LocalContext.current
    val uriHandler = LocalUriHandler.current
    val libraries = remember(context) {
        runCatching { Libs.Builder().withContext(context).build().libraries }
            .getOrDefault(emptyList())
    }

    Scaffold(
        topBar = {
            TopAppBar(
                title = {
                    Text(
                        text = stringResource(R.string.about),
                        maxLines = 1,
                        overflow = TextOverflow.Ellipsis,
                    )
                },
                navigationIcon = {
                    if (showBackButton) {
                        IconButton(onClick = onBack) {
                            Icon(
                                imageVector = Icons.AutoMirrored.Filled.ArrowBack,
                                contentDescription = stringResource(R.string.cd_back),
                            )
                        }
                    }
                },
            )
        },
    ) { innerPadding ->
        Box(
            modifier = Modifier
                .fillMaxSize()
                .padding(innerPadding),
            contentAlignment = Alignment.TopCenter,
        ) {
            LazyColumn(
                modifier = Modifier
                    .widthIn(max = AboutContentMaxWidth)
                    .fillMaxWidth(),
            ) {
                item(key = "header") {
                    Column(
                        modifier = Modifier
                            .fillMaxWidth()
                            .padding(24.dp),
                        horizontalAlignment = Alignment.CenterHorizontally,
                    ) {
                        Text(
                            text = stringResource(R.string.app_name),
                            style = MaterialTheme.typography.headlineMedium,
                        )
                        Spacer(Modifier.height(8.dp))
                        Text(
                            text = stringResource(
                                R.string.version,
                                BuildConfig.VERSION_NAME,
                                BuildConfig.VERSION_CODE,
                            ),
                            style = MaterialTheme.typography.bodyMedium,
                            color = MaterialTheme.colorScheme.onSurfaceVariant,
                        )
                    }
                }
                item(key = "application_header") {
                    SectionHeader(stringResource(R.string.app))
                }
                item(key = "github") {
                    AboutRow(
                        title = stringResource(R.string.ghrepo),
                        description = stringResource(R.string.view_source),
                        onClick = { runCatching { uriHandler.openUri(GITHUB_URL) } },
                    )
                }
                item(key = "libraries_header") {
                    SectionHeader(stringResource(R.string.deps_libs))
                }
                items(libraries) { library ->
                    val licenses = remember(library) {
                        library.licenses.joinToString(", ") { it.name }
                    }
                    val website = library.website
                    val onClick: (() -> Unit)? = if (website.isNullOrBlank()) {
                        null
                    } else {
                        {
                            runCatching { uriHandler.openUri(website) }
                            Unit
                        }
                    }
                    AboutRow(
                        title = library.name,
                        description = licenses,
                        onClick = onClick,
                    )
                }
                item(key = "bottom_spacer") { Spacer(Modifier.height(24.dp)) }
            }
        }
    }
}

@Composable
private fun AboutRow(
    title: String,
    description: String,
    onClick: (() -> Unit)?,
) {
    Row(
        modifier = Modifier
            .fillMaxWidth()
            .then(if (onClick != null) Modifier.clickable(onClick = onClick) else Modifier)
            .padding(start = 24.dp, end = 16.dp, top = 12.dp, bottom = 12.dp),
        verticalAlignment = Alignment.CenterVertically,
    ) {
        Column(modifier = Modifier.weight(1f)) {
            Text(
                text = title,
                style = MaterialTheme.typography.titleMedium,
                maxLines = 1,
                overflow = TextOverflow.Ellipsis,
            )
            if (description.isNotBlank()) {
                Text(
                    text = description,
                    style = MaterialTheme.typography.bodySmall,
                    color = MaterialTheme.colorScheme.onSurfaceVariant,
                    maxLines = 2,
                    overflow = TextOverflow.Ellipsis,
                )
            }
        }
    }
}
